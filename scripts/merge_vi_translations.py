def normalize(s: str) -> str:
    """Loose key for fuzzy lookup: collapse whitespace, drop trailing ellipsis/punct."""
    s = re.sub(r"\s+", "", s)
    s = s.rstrip("…:：!！?？，,.。 ")
    return s


def merge() -> None:
    target_path = JSON_PATHS[0]
    with target_path.open(encoding="utf-8") as f:
        data: dict[str, str] = json.load(f)

    added = 0
    skipped: list[str] = []

    # Pass 1: add explicit translations.
    for src, vi in {**ENUM_TRANSLATIONS, **EXTRA_TR_TRANSLATIONS}.items():
        if src in data:
            continue
        data[src] = vi
        added += 1

    # Pass 2: fuzzy-inherit translations for keys not yet covered.
    norm_index = {normalize(k): v for k, v in data.items()}
    missing_tr_path = Path("missing_tr.json")
    if missing_tr_path.exists():
        with missing_tr_path.open(encoding="utf-8") as f:
            missing = json.load(f)
        for src in missing:
            if src in data:
                continue
            inherited = norm_index.get(normalize(src))
            if inherited:
                data[src] = inherited
                added += 1
            else:
                skipped.append(src)

    # Sort keys alphabetically for diff readability.
    sorted_data = dict(sorted(data.items(), key=lambda kv: kv[0]))

    for path in JSON_PATHS:
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8") as f:
            json.dump(sorted_data, f, ensure_ascii=False, indent=2)

    print(f"added/updated: {added} entries (total now {len(sorted_data)})")
    print(f"still untranslated: {len(skipped)}")
    if skipped:
        with open("still_untranslated.json", "w", encoding="utf-8") as f:
            json.dump(skipped, f, ensure_ascii=False, indent=2)
        print("  list saved to still_untranslated.json")


if __name__ == "__main__":
    merge()
